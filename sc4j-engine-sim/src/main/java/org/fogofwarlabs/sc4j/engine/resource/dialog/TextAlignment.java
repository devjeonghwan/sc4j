package org.fogofwarlabs.sc4j.engine.resource.dialog;

/**
 * Names how the text of a control is aligned horizontally in its bounds.
 */
public enum TextAlignment {
    /**
     * The text starts at the left edge.
     */
    LEFT,
    /**
     * The text is centred.
     */
    CENTER,
    /**
     * The text ends at the right edge.
     */
    RIGHT
}
