package org.fogofwarlabs.sc4j.engine.client.input;

/**
 * Names a button of the pointer (mouse).
 */
public enum PointerButton {
    /**
     * The primary (left) button.
     */
    LEFT,
    /**
     * The secondary (right) button.
     */
    RIGHT,
    /**
     * The middle button or the pressed wheel.
     */
    MIDDLE,
    /**
     * The fourth button, often "back".
     */
    BUTTON_4,
    /**
     * The fifth button, often "forward".
     */
    BUTTON_5,
    /**
     * The sixth button.
     */
    BUTTON_6,
    /**
     * The seventh button.
     */
    BUTTON_7,
    /**
     * The eighth button.
     */
    BUTTON_8
}
